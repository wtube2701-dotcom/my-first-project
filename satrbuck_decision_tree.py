import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Load the datasets with appropriate encoding
drink_menu_df = pd.read_csv('/content/starbucks_drinkMenu_expanded.csv')
drink_nutr_df = pd.read_csv('/content/starbucks-menu-nutrition-drinks.csv')
food_nutr_df = pd.read_csv('/content/starbucks-menu-nutrition-food.csv', encoding='utf-16')

# Display basic information and shape of the datasets
print("Drink Menu Shape:", drink_menu_df.shape)
print("Drink Nutrition Shape:", drink_nutr_df.shape)
